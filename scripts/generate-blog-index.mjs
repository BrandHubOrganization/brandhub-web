import fs from "node:fs";
import path from "node:path";
import { registerHooks } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (
      (specifier.startsWith("./") || specifier.startsWith("../")) &&
      !path.extname(specifier) &&
      context.parentURL
    ) {
      const parentDir = path.dirname(fileURLToPath(context.parentURL));
      const tsCandidate = path.resolve(parentDir, `${specifier}.ts`);
      if (fs.existsSync(tsCandidate)) {
        return nextResolve(pathToFileURL(tsCandidate).href, context);
      }
    }
    return nextResolve(specifier, context);
  },
});

const dataDir = path.resolve(import.meta.dirname, "../src/data");

const BATCH_SOURCES = [
  { batchKey: "pillar", file: "blogPillarPosts.ts", exportName: "BLOG_PILLAR_POSTS" },
  { batchKey: "b1p1", file: "blogBatch1Part1.ts", exportName: "BLOG_BATCH1_PART1_POSTS" },
  { batchKey: "b1p2", file: "blogBatch1Part2.ts", exportName: "BLOG_BATCH1_PART2_POSTS" },
  { batchKey: "b2p1", file: "blogBatch2Part1.ts", exportName: "BLOG_BATCH2_PART1_POSTS" },
  { batchKey: "b2p2", file: "blogBatch2Part2.ts", exportName: "BLOG_BATCH2_PART2_POSTS" },
  { batchKey: "b2p3", file: "blogBatch2Part3.ts", exportName: "BLOG_BATCH2_PART3_POSTS" },
  { batchKey: "b3p1", file: "blogBatch3Part1.ts", exportName: "BLOG_BATCH3_PART1_POSTS" },
  { batchKey: "b3p2", file: "blogBatch3Part2.ts", exportName: "BLOG_BATCH3_PART2_POSTS" },
  { batchKey: "b4p1", file: "blogBatch4Part1.ts", exportName: "BLOG_BATCH4_PART1_POSTS" },
  { batchKey: "b4p2", file: "blogBatch4Part2.ts", exportName: "BLOG_BATCH4_PART2_POSTS" },
];

const summaries = [];

for (const src of BATCH_SOURCES) {
  const mod = await import(pathToFileURL(path.join(dataDir, src.file)).href);
  const posts = mod[src.exportName];
  for (const p of posts) {
    summaries.push({
      id: p.id,
      topicNumber: p.topicNumber,
      slug: p.slug,
      title: p.title,
      metaTitle: p.metaTitle,
      metaDescription: p.metaDescription,
      category: p.category,
      primaryKeyword: p.primaryKeyword,
      secondaryKeywords: p.secondaryKeywords,
      hashtags: p.hashtags,
      searchIntent: p.searchIntent,
      targetRoles: p.targetRoles,
      publishedAt: p.publishedAt,
      updatedAt: p.updatedAt,
      readingTimeMinutes: p.readingTimeMinutes,
      authorId: p.author.id,
      coverImage: p.coverImage,
      coverImageAlt: p.coverImageAlt,
      geoSummary: p.geoSummary,
      keyTakeaways: p.keyTakeaways,
      relatedSlugs: p.relatedSlugs,
      batchKey: src.batchKey,
    });
  }
}

const outLines = [
  "// AUTO-GENERATED BY scripts/generate-blog-index.mjs — DO NOT EDIT MANUALLY",
  'import { BLOG_AUTHORS } from "./blogAuthors";',
  'import type { BlogPostSummary } from "./blogTypes";',
  "",
  "export const BLOG_POST_SUMMARIES: BlogPostSummary[] = [",
  ...summaries.map((s) => {
    const { authorId, ...rest } = s;
    const jsonObj = JSON.stringify(rest, null, 2)
      .split("\n")
      .map((line, i) => (i === 0 ? `  {` : `  ${line}`))
      .join("\n");
    return jsonObj.replace(
      /\n  \}$/,
      `,\n    "author": BLOG_AUTHORS[${JSON.stringify(authorId)}]\n  },`,
    );
  }),
  "];",
  "",
];

const outPath = path.join(dataDir, "blogPostIndex.ts");
fs.writeFileSync(outPath, outLines.join("\n"), "utf8");
console.log(`[generate-blog-index] Wrote ${summaries.length} post summaries to src/data/blogPostIndex.ts.`);
