export const mockTaskService = {
  getWorkspaceTasks: (params: TaskListFilterParams = {}): PagedTaskResponse => {
    let items = [...MOCK_TASKS];

    if (params.status && params.status !== "ALL") {
      items = items.filter((t) => t.status === params.status);
    }
    if (params.type && params.type !== "ALL") {
      items = items.filter((t) => t.type === params.type);
    }
    if (params.search) {
      const query = params.search.toLowerCase();
      items = items.filter((t) => t.name.toLowerCase().includes(query));
    }

    const sortField = params.sort ?? "createdAt";
    const isAsc = params.direction === "asc";

    items.sort((a, b) => {
      let valA = a[sortField as keyof TaskListItem] ?? "";
      let valB = b[sortField as keyof TaskListItem] ?? "";
      if (valA < valB) return isAsc ? -1 : 1;
      if (valA > valB) return isAsc ? 1 : -1;
      return 0;
    });

    const page = params.page ?? 0;
    const size = params.size ?? 20;
    const start = page * size;
    const paginated = items.slice(start, start + size);

    return {
      content: paginated,
      page,
      size,
      totalElements: items.length,
      totalPages: Math.ceil(items.length / size) || 1,
      last: start + size >= items.length,
    };
  },
};
